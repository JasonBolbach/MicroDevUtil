#!/bin/sh
# Regenerates src/ReservedMacros.h: every macro the generated code's translation unit defines (the headers it includes: Arduino compat, LovyanGFX,
# SuperGUI, and the C / C++ library headers they pull in). A control, group or form named like one of these would be rewritten by the
# preprocessor and break the generated sketch. Run from tools/FormDesigner after the headers (or LovyanGFX) change:   sh scripts/gen_reserved_macros.sh
set -e
cd "$(dirname "$0")/.."
SG=../..; LG=${LGFX_ROOT:-../../../LovyanGFX}
PROBE=$(mktemp -t fdprobe).cpp
{
  echo '#include <cstdio>'; echo '#include <cstdlib>'; echo '#include <cstdint>'; echo '#include <cmath>'; echo '#include <cstring>'; echo '#include <cctype>'
  echo '#include <algorithm>'; echo '#include <string>'; echo '#include <vector>'; echo '#include <functional>'
  echo '#include <Arduino.h>'; echo '#include <LovyanGFX.hpp>'
  for h in $SG/src/Super*.h; do echo "#include <$(basename "$h")>"; done
} > "$PROBE"
SDLI=$(sdl2-config --cflags 2>/dev/null || echo "-I/opt/homebrew/include/SDL2 -I/usr/include/SDL2")
OUT=src/ReservedMacros.h
{
  echo '// GENERATED by scripts/gen_reserved_macros.sh - do not edit. Macros defined by the headers the generated code includes (names starting with _ are'
  echo '// rejected by a rule in ReservedNames.h and are left out). Sorted with strcmp order, so IsMacroName() can binary-search it.'
  echo '#pragma once'
  echo 'namespace FD { static const char* const kReservedMacros[] = {'
  c++ -std=gnu++17 -E -dM -DLGFX_SDL $SDLI -I"$SG/src" -I"$SG/extras/desktop" -I"$SG/extras/desktop/compat" -I"$LG/src" "$PROBE" 2>/dev/null \
    | awk '{print $2}' | sed 's/(.*//' | grep -E '^[A-Za-z][A-Za-z0-9_]*$' | LC_ALL=C sort -u | sed 's/.*/    "&",/'
  echo '}; }'
} > "$OUT"
rm -f "$PROBE"
echo "wrote $OUT ($(grep -c '^    "' "$OUT") macro names)"
